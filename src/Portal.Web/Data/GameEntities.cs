using System.ComponentModel.DataAnnotations;

namespace Portal.Web.Data;

/// <summary>
/// Очки одного человека в игре «Разбор завала» — той самой пасхалке,
/// которая открывается десятью нажатиями на своё имя.
///
/// ЗАЧЕМ ВООБЩЕ ХРАНИТЬ
///
/// До сих пор игра не касалась сервера вовсе: сыграл, увидел число,
/// закрыл вкладку — и всё. Рейтинг превращает её в общее дело: число
/// имеет смысл, только когда его с чем-то сравнивают.
///
/// ОДНА СТРОКА НА ЧЕЛОВЕКА, А НЕ ЖУРНАЛ ПАРТИЙ
///
/// Напрашивается писать каждую партию отдельной строкой: тогда можно
/// посчитать что угодно потом. Но «потом» не наступит — спрашивают здесь
/// ровно одно: сколько у кого всего. Журнал партий ради этого означал бы
/// тысячи строк в месяц и запрос с группировкой при каждом открытии
/// страницы. Поэтому строка одна, и она прибавляется.
///
/// ЧТО ЭТО НЕ ЗНАЧИТ
///
/// Очки присылает браузер, и подделать их может любой, кто откроет
/// средства разработчика. Это сознательно принято: цена жульничества —
/// строка в шуточном рейтинге, а защита от него означала бы считать
/// игру на сервере. Поэтому очки нигде, кроме этой таблицы,
/// ни на что не влияют, и обнулить рейтинг может администратор.
/// </summary>
public class GameScore
{
    public int Id { get; set; }

    [MaxLength(256)]
    public string UserName { get; set; } = "";

    /// <summary>
    /// Имя, которым человек подписан в рейтинге. Хранится копией:
    /// рейтинг должен читаться и тогда, когда контроллер домена
    /// недоступен, — иначе в таблице будут одни логины.
    /// </summary>
    [MaxLength(256)]
    public string DisplayName { get; set; } = "";

    /// <summary>Сумма очков за всё время. Именно по ней строится рейтинг.</summary>
    public long Points { get; set; }

    /// <summary>Лучшая одиночная партия — рядом с суммой это видно сразу.</summary>
    public int Best { get; set; }

    /// <summary>Сколько партий сыграно.</summary>
    public int Games { get; set; }

    /// <summary>Когда играли в последний раз, UTC.</summary>
    public DateTime UpdatedAt { get; set; }
}
