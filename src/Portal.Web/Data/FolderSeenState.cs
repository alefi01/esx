using System.ComponentModel.DataAnnotations;

namespace Portal.Web.Data;

/// <summary>
/// Докуда человек дочитал объявления В ОДНОЙ ПАПКЕ.
///
/// ПОЧЕМУ ОТМЕТКА СТАЛА ПО ПАПКАМ
///
/// Раньше объявления жили одной лентой, и границы «прочитанного» хватало
/// одной на человека: номер последнего увиденного объявления, всё новее —
/// новое. Теперь объявление висит на папке, и лент столько же, сколько
/// папок с объявлениями.
///
/// С одной общей границей получилась бы неправда: человек открыл папку
/// своего отдела — и прочитанными стали заодно объявления всех остальных
/// отделов, просто потому что они старше. Поэтому отметка у каждой папки
/// своя.
///
/// Строка заводится, только когда человек впервые открыл папку
/// с объявлениями: таблица не должна расти на каждого человека
/// умножить на каждую папку хранилища.
/// </summary>
public class FolderSeenState
{
    public int Id { get; set; }

    [MaxLength(256)]
    public string UserName { get; set; } = "";

    public int FolderId { get; set; }
    public StorageFolder? Folder { get; set; }

    /// <summary>Номер последнего объявления этой папки, которое человек видел.</summary>
    public int LastSeenAnnouncementId { get; set; }

    public DateTime UpdatedAt { get; set; }
}
