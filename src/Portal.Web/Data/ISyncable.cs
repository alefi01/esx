namespace Portal.Web.Data;

/// <summary>
/// Объект, который расходится по филиалам.
///
/// Три поля, которые нужны любому такому объекту:
///
///   GlobalId     — общий для всех филиалов номер. Обычный Id для этого
///                  не годится: базы у филиалов разные, и объявление №5
///                  в первом офисе не имеет отношения к объявлению №5
///                  во втором.
///
///   OriginBranch — где объект создан. Нужен человеку («объявление
///                  из Офиса 2») и коду при разборе спорных случаев.
///
///   ChangedAt    — когда объект последний раз менялся, UTC. По нему
///                  решается спор, если один объект правили сразу
///                  в двух филиалах: побеждает более позднее изменение.
/// </summary>
public interface ISyncable
{
    Guid GlobalId { get; set; }

    string OriginBranch { get; set; }

    DateTime ChangedAt { get; set; }
}
