using System.ComponentModel.DataAnnotations;

namespace Portal.Web.Data;

/// <summary>
/// Что пользователь уже видел. Одна строка на человека.
///
/// ПОЧЕМУ ТАК, А НЕ ТАБЛИЦА «УВЕДОМЛЕНИЯ»
///
/// Напрашивается завести таблицу уведомлений и класть туда по строке
/// на каждого получателя при каждом событии. При двадцати сотрудниках
/// и одном объявлении это двадцать строк — и так на каждое объявление,
/// на каждое сообщение. Таблица растёт, её надо чистить, а пользы ноль.
///
/// Здесь другой подход: события уже хранятся (объявления — в своей таблице,
/// сообщения будут в своей), а на человека приходится ровно одна отметка
/// «докуда я всё видел». Непрочитанное — это то, что новее отметки.
/// Ни роста, ни чистки, ни рассинхронизации.
/// </summary>
public class UserSeenState
{
    public int Id { get; set; }

    /// <summary>Логин (sAMAccountName). Ключ, по которому всё и ищется.</summary>
    [MaxLength(256)]
    public string UserName { get; set; } = "";

    /// <summary>
    /// Как показывать этого человека. Обновляется при каждом входе.
    ///
    /// Нужно для переписок: если контроллер домена недоступен, список
    /// собеседников всё равно можно собрать из тех, кто уже входил
    /// в портал, — но без имени в этом списке будут одни логины.
    /// </summary>
    [MaxLength(256)]
    public string DisplayName { get; set; } = "";

    /// <summary>
    /// Номер последнего объявления, которое человек видел.
    /// Всё, что новее, считается непрочитанным.
    /// </summary>
    public int LastSeenAnnouncementId { get; set; }

    /// <summary>
    /// Время, до которого человек видел личные сообщения.
    /// Понадобится на этапе переписок; сейчас поле просто существует,
    /// чтобы потом не делать ещё одну миграцию из-за одной колонки.
    /// </summary>
    public DateTime? LastSeenMessagesAt { get; set; }

    /// <summary>Когда отметка последний раз обновлялась — для разбора жалоб.</summary>
    public DateTime UpdatedAt { get; set; }

    /// <summary>
    /// Когда человек последний раз что-то делал в портале, UTC.
    ///
    /// Отсюда берётся «в сети» и «был в сети в 14:20» в переписках.
    /// «В сети» — это не постоянное соединение, а «шевелился недавно»:
    /// портал засекает время при каждом запросе страницы и при каждом
    /// опросе колокольчика, который идёт раз в минуту, пока вкладка
    /// открыта. Держать ради статуса открытый канал на каждого человека
    /// было бы несоразмерно: канал между офисами узкий, а точность
    /// «плюс-минус минута» здесь никому не нужна.
    ///
    /// Пусто — человек ни разу не заходил после обновления портала.
    /// </summary>
    public DateTime? LastActiveAt { get; set; }
}
