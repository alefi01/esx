namespace Portal.Web.Pages.Shared;

/// <summary>
/// Вкладки раздела «Задачи».
///
/// ЗАЧЕМ ОТДЕЛЬНОЙ МОДЕЛЬЮ
///
/// Половины раздела живут на разных страницах: у них разные права
/// и разные обработчики. А выглядеть они должны как один раздел
/// с вкладками, иначе получается три пункта меню про задачи. Общая
/// разметка переключателя лежит здесь, чтобы вкладки не разъехались
/// при правке одной из страниц.
/// </summary>
/// <param name="Current">Какая вкладка открыта: own, head, assigned.</param>
/// <param name="HeadCount">
/// Сколько задач от руководителя требует внимания: новые, возвращённые
/// на доработку и просроченные.
/// </param>
/// <param name="WaitingCount">
/// Сколько подчинённые сдали на проверку — это и есть работа
/// начальника на его вкладке.
/// </param>
/// <param name="HasHead">
/// Человеку когда-либо что-то поручали. Начальник тоже бывает чьим-то
/// подчинённым, поэтому убирать вкладку «От руководителя» по должности
/// нельзя; но тому, кому никто ничего не поручал, она обещает раздел,
/// которого нет.
/// </param>
public sealed record TasksTabs(string Current, int HeadCount, int WaitingCount, bool HasHead = true);
