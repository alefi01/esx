namespace Portal.Web.Pages.Shared;

/// <summary>
/// Переключатель «Мои / Подчинённым» в заголовке раздела «Задачи».
///
/// ЗАЧЕМ ОТДЕЛЬНОЙ МОДЕЛЬЮ
///
/// Обе половины раздела — свои задачи и поставленные другим — живут
/// на разных страницах: у них разные обработчики и разные права.
/// А выглядеть они должны как один раздел с двумя вкладками, иначе
/// получается два пункта меню про одно и то же. Общая разметка
/// переключателя лежит здесь, чтобы вкладки не разъехались при правке
/// одной из страниц.
/// </summary>
/// <param name="Mine">Открыта половина «Мои» (иначе — «Подчинённым»).</param>
/// <param name="MineCount">Сколько своих задач требует внимания.</param>
/// <param name="WaitingCount">Сколько сдано на проверку — работа начальника.</param>
public sealed record TasksTabs(bool Mine, int MineCount, int WaitingCount);
