namespace Portal.Web.Configuration;

/// <summary>Секция "Storage" в appsettings.json.</summary>
public sealed class StorageOptions
{
    public const string SectionName = "Storage";

    /// <summary>
    /// Папка на диске, где физически лежат файлы.
    ///
    /// Держите её ВНЕ папки приложения: иначе при обновлении портала командой
    /// dotnet publish можно случайно затереть или удалить документы.
    /// Хорошее место — отдельный диск, например D:\PortalFiles.
    /// Именно эту папку потом будет реплицировать DFS-R на этапе 6.
    /// </summary>
    public string RootPath { get; set; } = "";

    /// <summary>
    /// Предел размера одного файла по умолчанию, мегабайты.
    /// Применяется к папкам, где своё значение не задано и не унаследовано.
    /// </summary>
    public int DefaultMaxFileSizeMb { get; set; } = 500;

    /// <summary>
    /// Жёсткий верхний предел размера ОДНОГО файла, мегабайты.
    /// Больше него нельзя выставить ни одной папке, и на это же значение
    /// настраиваются ограничения на размер запроса в ASP.NET Core.
    ///
    /// <b>0 — без ограничения.</b> Тогда портал не ставит предела вовсе,
    /// и единственным ограничителем остаётся IIS (см. ниже) и место на диске.
    ///
    /// ВАЖНО: у IIS ограничение своё, в web.config (maxAllowedContentLength).
    /// Его надо держать не меньше этого значения, иначе крупные файлы будут
    /// обрываться ещё до того, как запрос дойдёт до приложения, — с невнятной
    /// ошибкой 404.13 вместо понятного сообщения.
    ///
    /// Прежде здесь стояло 200 МБ. Для рабочих архивов и видео этого мало,
    /// поэтому значение поднято; настройка осталась на месте.
    /// </summary>
    public int AbsoluteMaxFileSizeMb { get; set; } = 4096;

    /// <summary>Предел не задан — принимаем файл любого размера.</summary>
    public bool FileSizeUnlimited => AbsoluteMaxFileSizeMb <= 0;

    /// <summary>
    /// Расширения, которые запрещено загружать.
    ///
    /// Смысл не в том, что портал «поймает вирус», — он этого не умеет.
    /// Смысл в том, чтобы хранилище внутри домена не стало удобной площадкой
    /// для раздачи исполняемых файлов: ссылку на такой файл легко разослать,
    /// и она выглядит как ссылка на внутренний доверенный ресурс.
    /// Список можно менять; сравнение без учёта регистра.
    /// </summary>
    public string[] BlockedExtensions { get; set; } =
    [
        ".exe", ".com", ".bat", ".cmd", ".msi", ".msp", ".scr", ".pif", ".cpl",
        ".dll", ".sys", ".drv", ".ocx", ".jar", ".hta", ".lnk", ".scf", ".reg",
        ".ps1", ".psm1", ".vbs", ".vbe", ".js", ".jse", ".wsf", ".wsh", ".chm",
        ".ade", ".adp", ".mde", ".msc", ".ins", ".isp", ".cer"
    ];

    /// <summary>
    /// Сколько дней файлы лежат в корзине, прежде чем будут стёрты с диска
    /// безвозвратно. 0 — стирать сразу, корзина фактически отключена.
    /// </summary>
    public int TrashRetentionDays { get; set; } = 30;

    /// <summary>
    /// Общий выключатель фоновой уборки: и автоочистки папок по сроку,
    /// и вычистки корзины. Пригодится, если понадобится срочно остановить
    /// удаление, не трогая настройки каждой папки.
    /// </summary>
    public bool CleanupEnabled { get; set; } = true;

    /// <summary>Как часто просыпается фоновая уборка, часы.</summary>
    public int CleanupIntervalHours { get; set; } = 6;

    /// <summary>
    /// Сколько дней хранить записи журнала действий. 0 — хранить вечно.
    ///
    /// Журнал растёт молча и не мешает работе, пока однажды не займёт
    /// заметную часть базы. Полгода — разумная середина: разбирательства
    /// «кто удалил документ» случаются по горячим следам, а через год
    /// такая запись уже никому не нужна.
    ///
    /// Старые записи убирает та же фоновая уборка, что чистит корзину.
    /// </summary>
    public int AuditRetentionDays { get; set; } = 180;

    /// <summary>Сколько записей журнала действий показывать на странице.</summary>
    public int AuditPageSize { get; set; } = 50;

    /// <summary>
    /// Сколько всего места отведено под хранилище, гигабайты.
    ///
    /// Это НЕ ограничение: портал ничего не запрещает по достижении этого
    /// числа. Оно нужно только для карточки в боковом меню — чтобы человек
    /// видел «занято 12 из 200 ГБ», а не голое «занято 12 ГБ», по которому
    /// невозможно понять, много это или мало.
    ///
    /// Ставьте сюда размер диска или той его части, которую вы готовы отдать
    /// под файлы портала. <b>0 — не показывать долю, только занятый объём.</b>
    /// </summary>
    public int TotalCapacityGb { get; set; } = 200;
}
