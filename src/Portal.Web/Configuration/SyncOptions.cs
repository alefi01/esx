namespace Portal.Web.Configuration;

/// <summary>
/// Синхронизация между филиалами.
///
/// ЗАЧЕМ ЭТО НУЖНО
///
/// Раньше портал стоял в одном офисе и обслуживал все филиалы сразу.
/// В своём офисе он работал быстро, в остальных — как позволял канал
/// между площадками. Теперь портал ставится в КАЖДОМ филиале, и филиалы
/// обмениваются между собой объявлениями, перепиской и файлами.
///
/// Человек всегда работает со СВОИМ сервером: и когда читает, и когда
/// загружает файл. Уже загруженное расходится по остальным филиалам
/// в фоне, по расписанию, и дальше в каждом филиале лежит своя копия.
/// Поэтому открытие файла из соседнего офиса не тянет его по каналу
/// заново — файл уже на месте.
///
/// КАК УСТРОЕН ОБМЕН
///
/// Каждый портал ведёт «журнал изменений» (таблица SyncOutbox): любое
/// изменение объявления, сообщения или файла добавляет туда запись
/// с возрастающим номером. Соседи по расписанию СПРАШИВАЮТ у него
/// «что появилось после номера N» и применяют полученное у себя.
///
/// Почему спрашивают, а не присылают: спрашивающему не нужно знать,
/// доступен ли сосед прямо сейчас, и не нужно ничего копить при обрыве
/// связи. Канал упал — сосед просто спросит позже, с того же номера,
/// и ничего не потеряется. Никаких очередей и повторных отправок.
///
/// Связь «каждый с каждым»: филиал 1 спрашивает у 2 и у 3, филиал 2 —
/// у 1 и у 3, и так далее. Пересылать чужие изменения дальше НЕ НУЖНО,
/// и это сделано намеренно: пересылка означала бы, что одно и то же
/// изменение может прийти двумя путями и закольцеваться.
///
/// СПОРНЫЕ СЛУЧАИ
///
/// Если один и тот же объект правили в двух филиалах одновременно,
/// побеждает правка с более поздним временем изменения. Это решение
/// принято сознательно: оно простое и предсказуемое. Другие схемы
/// (слияние текстов, ручной разбор конфликтов) в работе портала
/// не оправдывают своей сложности.
/// </summary>
public class SyncOptions
{
    public const string SectionName = "Sync";

    /// <summary>
    /// Включена ли синхронизация вообще.
    ///
    /// Пока филиал один — оставьте false, и портал будет работать
    /// ровно как раньше, без единого лишнего запроса.
    /// </summary>
    public bool Enabled { get; set; }

    /// <summary>
    /// Код ЭТОГО филиала: office1, office2, office3.
    ///
    /// Совпадает с кодом офиса из секции Offices. Именно им подписываются
    /// все изменения, сделанные на этом сервере, — чтобы в любом филиале
    /// было видно, откуда пришло объявление или файл.
    ///
    /// ВАЖНО: код должен быть РАЗНЫМ на разных серверах. Два сервера
    /// с одним кодом будут считать изменения друг друга своими,
    /// и обмен работать не будет.
    /// </summary>
    public string BranchCode { get; set; } = "";

    /// <summary>Как называется этот филиал для человека: «Офис 1».</summary>
    public string BranchName { get; set; } = "";

    /// <summary>
    /// Общий пароль обмена. Одинаковый на ВСЕХ серверах филиалов.
    ///
    /// Портал сравнивает его с заголовком X-Portal-Sync-Key в каждом
    /// запросе синхронизации. Без совпадения запрос отклоняется.
    /// Пустой пароль означает, что обмен выключен: отдавать содержимое
    /// портала кому угодно, кто дотянулся до порта, нельзя.
    ///
    /// Придумайте длинную случайную строку и пропишите её одинаково
    /// во всех филиалах. Хранить её лучше не в appsettings.json,
    /// а в переменной окружения Sync__Key — тогда она не попадёт
    /// в резервные копии конфигурации.
    /// </summary>
    public string Key { get; set; } = "";

    /// <summary>Соседние филиалы, у которых спрашивать изменения.</summary>
    public List<SyncPeer> Peers { get; set; } = [];

    /// <summary>
    /// Как часто спрашивать соседей, минуты. Значение по умолчанию;
    /// в панели администратора его можно поменять без перезапуска.
    /// </summary>
    public int DefaultIntervalMinutes { get; set; } = 15;

    /// <summary>
    /// Сколько записей журнала забирать за один запрос.
    ///
    /// Немного намеренно: между офисами канал узкий, и лучше сделать
    /// десять коротких запросов, чем один длинный, который оборвётся
    /// на середине и начнётся заново.
    /// </summary>
    public int BatchSize { get; set; } = 200;

    /// <summary>
    /// Размер куска при передаче файла, килобайты.
    ///
    /// Файлы передаются частями по той же причине: оборванная передача
    /// стоит одного куска, а не всего файла. 256 КБ — разумная середина
    /// между числом запросов и ценой повтора.
    /// </summary>
    public int ChunkSizeKb { get; set; } = 256;

    /// <summary>Сколько ждать ответа соседа, секунды.</summary>
    public int TimeoutSeconds { get; set; } = 60;

    /// <summary>
    /// Сколько дней хранить журнал изменений.
    ///
    /// Записи старше этого срока удаляются: они уже забраны соседями,
    /// а таблица иначе растёт без конца. Срок должен быть заведомо больше
    /// самого долгого возможного простоя филиала — иначе сервер, который
    /// стоял выключенным дольше, пропустит изменения безвозвратно.
    /// </summary>
    public int OutboxRetentionDays { get; set; } = 60;
}

/// <summary>Соседний филиал.</summary>
public class SyncPeer
{
    /// <summary>Его код: office2. Должен совпадать с его собственным BranchCode.</summary>
    public string Code { get; set; } = "";

    /// <summary>Название для человека: «Офис 2».</summary>
    public string Name { get; set; } = "";

    /// <summary>
    /// Адрес его портала: http://ftp2.domen.pro или http://192.168.112.10.
    /// Без косой черты на конце — она добавится сама.
    /// </summary>
    public string BaseUrl { get; set; } = "";
}
