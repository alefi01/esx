namespace Portal.Web.Configuration;

/// <summary>
/// Как портал называется и чем подписан.
///
/// ЗАЧЕМ ОТДЕЛЬНАЯ НАСТРОЙКА
///
/// Название организации меняется реже, чем что-либо ещё, но меняется:
/// переименование, слияние, новый бренд. Зашитое в разметку название
/// означало бы пересборку и повторное развёртывание портала ради одной
/// строки. Здесь же достаточно поправить appsettings.json на сервере
/// и перезапустить пул приложений.
///
/// Значения по умолчанию намеренно нейтральные: портал должен работать
/// сразу после установки, ещё до того как до него дойдут руки.
/// </summary>
public class BrandingOptions
{
    public const string SectionName = "Branding";

    /// <summary>
    /// Крупная надпись в шапке и вторая часть заголовка вкладки браузера.
    /// Коротко: это видно в каждой вкладке, длинное название там обрежется.
    /// </summary>
    public string Title { get; set; } = "Портал";

    /// <summary>Мелкая подпись под названием в шапке.</summary>
    public string Subtitle { get; set; } = "корпоративный портал";

    /// <summary>
    /// Значок в квадрате слева от названия и он же — значок вкладки браузера.
    ///
    /// Имя одного из встроенных значков БЕЗ приставки «i-»: folder, home,
    /// mega, star, users, chat, info, shield… Полный список — в _Icons.cshtml.
    /// Рисуются они кодом, поэтому картинок на сервер класть не нужно.
    ///
    /// Если у организации есть собственный логотип, положите его файлом
    /// в wwwroot/img/logo.svg (или .png) и укажите путь в LogoFile —
    /// он победит этот значок.
    /// </summary>
    public string LogoIcon { get; set; } = "building";

    /// <summary>
    /// Свой логотип картинкой: путь от корня сайта, например «/img/logo.svg».
    /// Пусто — рисуется встроенный значок из LogoIcon.
    ///
    /// Файл кладётся рядом с приложением, в папку wwwroot. Он же пойдёт
    /// в значок вкладки браузера, если это .svg, .png или .ico.
    /// </summary>
    public string LogoFile { get; set; } = "";

    /// <summary>Цвет квадрата с логотипом и значка вкладки.</summary>
    public string AccentColor { get; set; } = "#0067c0";
}
